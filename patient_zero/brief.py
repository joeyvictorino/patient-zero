"""One-page briefs generated from the profile, for people who do not build software.

`pz brief legislator`  ten questions to put to a vendor, a provider or a witness
`pz brief judge`       a scorecard for health AI pitches

Both are data (patient_zero/data/briefs.yaml) tied to control ids, so when a
control changes, a test says which question to revisit. Neither takes a
position on a bill, a vendor or a product.
"""
from __future__ import annotations

from importlib import resources
from typing import Any, Dict, Optional

import yaml

from . import buyer
from . import profile as profile_mod

AUDIENCES = ("legislator", "judge")


def load() -> Dict[str, Any]:
    return yaml.safe_load(resources.files("patient_zero").joinpath("data/briefs.yaml").read_text("utf-8"))


def render(audience: str, overlay: Optional[str] = None) -> str:
    if audience not in AUDIENCES:
        raise ValueError(f"audience must be one of {AUDIENCES}")
    doc = load()[audience]
    profile = profile_mod.load()
    known = {c.id for c in profile.controls}
    items = {i["id"]: i for i in buyer.load_overlay(overlay)["items"]} if overlay else {}
    laws = buyer.load_overlay(overlay)["laws"] if overlay else {}
    flag = f" --overlay {overlay}" if overlay else ""
    lines = [f"# {doc['title']}", "", f"Generated by `pz brief {audience}{flag}`. Do not edit by hand.", "", doc["intro"], ""]
    for number, q in enumerate(doc["questions"], 1):
        missing = [c for c in q["controls"] if c not in known]
        if missing:
            raise ValueError(f"brief question {number} names unknown controls: {missing}")
        lines += [f"## {number}. {q['ask']}", ""]
        if audience == "legislator":
            lines += [f"**Why it matters.** {q['why']}", "", f"**A good answer comes with.** {q['good']}", ""]
            rules = [items[i] for i in q.get("overlay", []) if i in items]
            if overlay:
                if rules:
                    for item in rules:
                        lines += [f"**{buyer.load_overlay(overlay)['name']} today ({laws[item['law']]['title'].split(',')[0]}, {item['cite']}).** "
                                  f"{item['statement']}", ""]
                else:
                    lines += [f"**{buyer.load_overlay(overlay)['name']} today.** This project's overlay lists no state rule on this question. "
                              "That is a statement about the overlay, not a finding that no rule exists.", ""]
        else:
            lines += ["| Score | What earns it |", "| --- | --- |", f"| 2 | {q['two']} |", "| 1 | Not done yet, with a specific plan and date. |",
                      "| 0 | Does not know, or claims it without being able to say who checked. |", ""]
        lines += [f"Safeguards behind this question: {', '.join(q['controls'])}.", ""]
    lines += ["---", "", doc["closing"], "",
              "From patient-zero, an open source project: https://github.com/joeyvictorino/patient-zero. Not legal advice."]
    return "\n".join(lines) + "\n"
