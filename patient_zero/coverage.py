"""What the tooling can and cannot test, computed from the code. Nothing here is hand-maintained."""
from __future__ import annotations

from typing import Dict, List

from .probes import agent, claims, isolation, restore, rls, stack
from .profile import Profile

PROBE_CONTROLS: Dict[str, List[str]] = {
    "isolation": isolation.CONTROLS,
    "agent": agent.CONTROLS,
    "egress": ["TRUST-1", "TRUST-2"],
    "tls": ["BASE-2"],
    "log": ["LOG-2"],
    "stack": stack.CONTROLS,
    "rls": rls.CONTROLS,
    "claims": claims.CONTROLS,
    "restore": restore.CONTROLS,
}

SAFEGUARD_CONTROLS: Dict[str, List[str]] = {
    "gate": ["GATE-1", "GATE-2", "GATE-4"],
    "auditlog": ["LOG-1", "LOG-2", "AGENT-1"],
    "egress": ["TRUST-1", "TRUST-2", "TRUST-3"],
    "phi": ["GATE-5", "AGENT-7"],
    "hidden": ["AGENT-4"],
    "policy": ["AGENT-2", "AGENT-3", "AGENT-6", "AGENT-7"],
    "custody": ["TEST-4"],
    "embedded": ["TEST-1"],
}


def rows(profile: Profile) -> List[Dict[str, object]]:
    out = []
    for control in profile.controls:
        probes = sorted(p for p, ids in PROBE_CONTROLS.items() if control.id in ids)
        safeguards = sorted(s for s, ids in SAFEGUARD_CONTROLS.items() if control.id in ids)
        support = ("probe and reference code" if probes and safeguards else "probe" if probes
                   else "reference code" if safeguards else "manual")
        out.append({"id": control.id, "family": control.family, "level": control.min_level,
                    "probes": probes, "safeguards": safeguards, "support": support})
    return out


def summary(profile: Profile) -> Dict[str, int]:
    table = rows(profile)
    return {
        "controls": len(table),
        "probes": len(PROBE_CONTROLS),
        "probed": sum(1 for r in table if r["probes"]),
        "with_reference_code": sum(1 for r in table if r["safeguards"]),
        "manual_only": sum(1 for r in table if r["support"] == "manual"),
    }


def markdown(profile: Profile) -> str:
    s = summary(profile)
    lines = [
        "# Coverage",
        "",
        "Generated by `pz coverage --markdown`. Do not edit by hand.",
        "",
        f"{s['probes']} probes touch {s['probed']} of {s['controls']} controls. {s['with_reference_code']} controls have reference code. "
        f"{s['manual_only']} have neither and need a person from start to finish.",
        "",
        "A probe can fail a control and can raise belief in it. It cannot pass one.",
        "",
        "| Control | Level | Probes | Reference code | Support |",
        "| --- | --- | --- | --- | --- |",
    ]
    for r in rows(profile):
        lines.append(f"| {r['id']} | {r['level']} | {', '.join(r['probes']) or 'none'} "
                     f"| {', '.join(r['safeguards']) or 'none'} | {r['support']} |")
    return "\n".join(lines) + "\n"


def profile_markdown(profile: Profile) -> str:
    lines = [
        f"# The profile, version {profile.version} ({profile.status})",
        "",
        "Generated from `patient_zero/data/controls.yaml` by `pz controls --markdown`. Do not edit by hand.",
        "",
    ]
    for level, meta in profile.levels.items():
        lines.append(f"- **{level} {meta['name']}:** {meta['summary']} ({len(profile.for_level(level))} controls)")
    lines.append("")
    for family, meta in profile.families.items():
        lines += [
            f"## {family}: {meta['name']}",
            "",
            meta["principle"],
            "",
            f"HIPAA {', '.join(meta['hipaa'])}. SP 800-53 {', '.join(meta['sp800_53'])}. CSF {', '.join(meta['csf'])}.",
            "",
        ]
        for control in profile.for_family(family):
            lines.append(f"- **{control.id}** ({control.min_level}) {control.statement}")
        lines.append("")
    checked = f"HIPAA citations were checked to exist in eCFR on {profile.hipaa_citations_checked}. " if profile.hipaa_citations_checked else ""
    lines.append(f"{checked}SP 800-53 and CSF identifiers are unchecked. The fit of every mapping is the author's judgment, not a legal opinion.")
    return "\n".join(lines) + "\n"
