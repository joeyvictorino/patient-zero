"""The buyer's side: plain language for people who choose AI tools rather than build them.

A clinic manager cannot run a probe, but can ask a vendor the right question
and know what a good answer comes with. This module turns the profile into a
vendor questionnaire and turns an assessment into a one-page summary.
"""
from __future__ import annotations

from datetime import date
from importlib import resources
from typing import Any, Dict, List, Optional

import yaml

from .assess import summarize
from .profile import Profile


def load_plain() -> Dict[str, Dict[str, str]]:
    return yaml.safe_load(resources.files("patient_zero").joinpath("data/plain.yaml").read_text("utf-8"))


def overlays() -> List[str]:
    folder = resources.files("patient_zero").joinpath("data/overlays")
    return sorted(p.name[:-5] for p in folder.iterdir() if p.name.endswith(".yaml"))


def load_overlay(name: str) -> Dict[str, Any]:
    if name not in overlays():
        raise ValueError(f"unknown overlay: {name} (available: {', '.join(overlays())})")
    return yaml.safe_load(resources.files("patient_zero").joinpath(f"data/overlays/{name}.yaml").read_text("utf-8"))


def overlay_markdown(name: str) -> str:
    data = load_overlay(name)
    lines = [
        f"# {data['name']} overlay",
        "",
        f"Generated by `pz overlay {name} --markdown`. Do not edit by hand.",
        "",
        f"State requirements that sit on top of HIPAA for AI products used in {data['name']}. Checked against the sources below on "
        f"{data['checked']}. These are one person's reading of the law, not legal advice. Confirm with {data['name']} counsel.",
        "",
    ]
    for key, law in data["laws"].items():
        lines.append(f"- **{key}:** [{law['title']}]({law['source']}), effective {law['effective']}")
    lines.append("")
    for item in data["items"]:
        lines += [
            f"## {item['id']}: {item['plain']}",
            "",
            f"**Requirement ({item['law']} {item['cite']}).** {item['statement']}",
            "",
            f"**Applies to:** {item['applies']}.",
            "",
            f"**Ask the vendor:** {item['ask']}",
            "",
            f"**A good answer comes with:** {item['proof']}",
            "",
        ]
    return "\n".join(lines)


def questionnaire(profile: Profile, level: str = "L1", overlay: Optional[str] = None) -> str:
    plain = load_plain()
    controls = profile.for_level(level)
    lines = [
        f"# Questions to ask an AI vendor before they touch patient data (level {level})",
        "",
        f"Generated by `pz questionnaire --level {level}" + (f" --overlay {overlay}" if overlay else "") + "`. Do not edit by hand.",
        "",
        f"{len(controls)} questions in plain language. For each one: what it means, the question to ask, and what a good answer comes with. "
        "A vendor who answers yes but cannot produce the item in the last column has not answered.",
        "",
        "How to use it: send the list, ask for written answers with the evidence attached, and ask that the evidence be sealed "
        "(`pz seal`) so you can confirm nothing was edited afterward. This list helps you ask better questions. It is not legal advice "
        "and it does not replace a Business Associate Agreement or your own counsel.",
        "",
    ]
    number = 0
    for family, meta in profile.families.items():
        rows = [c for c in controls if c.family == family]
        if not rows:
            continue
        lines += [f"## {meta['name']}", "", "| # | What it means | Ask the vendor | A good answer comes with |", "| --- | --- | --- | --- |"]
        for c in rows:
            number += 1
            p = plain[c.id]
            lines.append(f"| {number} ({c.id}) | {p['plain']} | {p['ask']} | {p['proof']} |")
        lines.append("")
    if overlay:
        data = load_overlay(overlay)
        lines += [f"## {data['name']} law", "", "| # | What it means | Ask the vendor | A good answer comes with |", "| --- | --- | --- | --- |"]
        for item in data["items"]:
            number += 1
            proof = item["proof"].replace("|", "\\|")
            lines.append(f"| {number} ({item['id']}) | {item['plain']} Applies to {item['applies']}. | {item['ask']} | {proof} |")
        lines += ["", f"See the {data['name']} overlay for the legal citations. Confirm with counsel."]
        lines.append("")
    return "\n".join(lines)


def executive_summary(assessment: Dict[str, Any], profile: Profile) -> str:
    """One page, no jargon, for the person who has to decide."""
    plain = load_plain()
    summary = summarize(assessment, profile)
    level = summary["level"]
    by_status: Dict[str, List[str]] = {}
    for control in profile.for_level(level):
        status = assessment["controls"].get(control.id, {}).get("status", "not_assessed")
        by_status.setdefault(status, []).append(control.id)
    failed, partial = by_status.get("fail", []), by_status.get("partial", [])
    passed, unchecked = by_status.get("pass", []), by_status.get("not_assessed", [])
    total = summary["required"]

    lines = [f"# {summary['product']}: readiness for patient data", "", f"Summary for decision makers, {date.today().isoformat()}.", ""]
    if summary["conformant"]:
        lines.append(f"**Bottom line: every one of the {total} safeguards has been checked and confirmed by a person with evidence.**")
    elif failed:
        lines.append(f"**Bottom line: not ready. {len(failed)} of {total} safeguards failed a test.** "
                     "Patient data should not go into this product until they are fixed and retested.")
    else:
        lines.append(f"**Bottom line: not yet shown to be ready.** Nothing has failed, but only {len(passed)} of {total} safeguards "
                     "have been confirmed by a person with evidence.")
    lines += ["", f"Confirmed: {len(passed)}. Tested clean by software, awaiting a person's sign-off: {len(partial)}. "
              f"Failed: {len(failed)}. Not checked at all: {len(unchecked)}.", ""]
    if failed:
        lines += ["## What failed", ""]
        for cid in failed:
            note = assessment["controls"][cid].get("note") or ""
            lines.append(f"- **{plain[cid]['plain']}** This is not true today." + (f" What the test found: {note}." if note else ""))
        lines.append("")
    if partial:
        lines += ["## Tested by software, still needs a person", "",
                  "An automated test found no problem here. That is weak evidence, not proof, and nobody has signed off.", ""]
        lines += [f"- {plain[cid]['plain']}" for cid in partial]
        lines.append("")
    if unchecked:
        lines += ["## Not checked yet", "",
                  f"{len(unchecked)} safeguards have no test result and no sign-off. The first questions to put to the vendor:", ""]
        lines += [f"- {plain[cid]['ask']}" for cid in unchecked[:6]]
        if len(unchecked) > 6:
            lines.append(f"- and {len(unchecked) - 6} more, in the vendor questionnaire (`pz questionnaire`).")
        lines.append("")
    lines += ["## What this summary is", "",
              "It reports tests and sign-offs recorded for this product. It is not a HIPAA certification, which does not exist, "
              "and it is not legal advice. A clean software test never counts as confirmed; "
              "only a named person with evidence can confirm a safeguard.", ""]
    return "\n".join(lines)
